/**
 * Migration test for the rename to dsh-wrainrock-daemon.
 *
 * For every former name this project had — `dsh-ian-daemon`, and before it
 * `dsh-autostart`/`dsh-harness` — this recreates an install made under that name
 * (data directory, enabled unit carrying that generation's marker) and checks
 * that ONE install() call with the DEFAULT legacy settings carries the data
 * over, retires the legacy unit and leaves exactly the new unit enabled.
 *
 * Everything happens under .migration-test/ with a fake unit directory, so the
 * real ~/.dsh and ~/.config/systemd/user are never touched. The one real side
 * effect is a `daemon-reload` of the user manager, which is idempotent.
 *
 *   node tests/migration.mjs
 */
import { existsSync, lstatSync, mkdirSync, rmSync, symlinkSync, writeFileSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createManager } from '../index.js'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, '..', '.migration-test')
const NEW_MARKER = '@local/dsh-wrainrock-daemon'
const NEW_HOME = 'wrainrock-daemon'
const NEW_UNIT = 'dsh-wrainrock-daemon.service'

let failed = 0
const check = (what, expected, actual) => {
  if (String(expected) === String(actual)) {
    console.log(`  ok   ${what}`)
  } else {
    console.log(`  FAIL ${what} (expected ${expected}, got ${actual})`)
    failed = 1
  }
}

const CASES = [
  {
    name: 'dsh-ian-daemon',
    home: 'ian-daemon',
    marker: '@local/dsh-ian-daemon',
    units: ['dsh-ian-daemon.service', 'dsh-ian-daemon-safemode.service', 'dsh-ian-daemon-selftest.service'],
  },
  {
    name: 'dsh-autostart',
    home: 'autostart',
    marker: '@local/dsh-autostart',
    units: ['dsh-harness.service', 'dsh-harness-safemode.service', 'dsh-autostart-selftest.service'],
  },
]

rmSync(ROOT, { recursive: true, force: true })

for (const [index, testCase] of CASES.entries()) {
  console.log(`${index + 1}. upgrading an install made under the former name ${testCase.name}`)
  const root = join(ROOT, testCase.name)
  const dshHome = join(root, 'dsh')
  const unitDir = join(root, 'systemd-user')
  const wants = join(unitDir, 'default.target.wants')
  const legacyHome = join(dshHome, testCase.home)
  const newHome = join(dshHome, NEW_HOME)

  // --- an install made under that former name -------------------------------
  mkdirSync(join(legacyHome, 'state'), { recursive: true })
  mkdirSync(join(legacyHome, 'reports'), { recursive: true })
  writeFileSync(join(legacyHome, 'state', 'mode'), 'normal', 'utf8')
  writeFileSync(join(legacyHome, 'reports', 'old.md'), '# old report\n', 'utf8')
  mkdirSync(wants, { recursive: true })
  writeFileSync(join(unitDir, testCase.units[0]),
    `# Generated by the ${testCase.marker} plugin\n[Unit]\nDescription=old main\n[Service]\nExecStart=/bin/true\n[Install]\nWantedBy=default.target\n`, 'utf8')
  symlinkSync(join('..', testCase.units[0]), join(wants, testCase.units[0]))
  // A unit of that generation which this project did NOT write: it must survive.
  writeFileSync(join(unitDir, testCase.units[1]),
    '[Unit]\nDescription=somebody else\n[Service]\nExecStart=/bin/true\n', 'utf8')

  // DEFAULT legacy settings: no legacyHomeDir / legacyHomeDirs / legacyUnitNames
  // override, and the home directory is left at its default too — so this is the
  // real upgrade path an already-installed machine takes.
  const manager = createManager({ logger: console }, {
    dshHome,
    unitDir,
    cliPath: fileURLToPath(new URL('../package.json', import.meta.url)),
    nodeBin: process.execPath,
    enableLinger: false,
    installOnActivate: false,
    port: 3080,
  })
  const result = await manager.install({ start: false, linger: false })

  check('the data directory was carried over', 'true', existsSync(join(newHome, 'state', 'mode')))
  check('the old state came along', 'normal', readFileSync(join(newHome, 'state', 'mode'), 'utf8'))
  check('the old reports came along', 'true', existsSync(join(newHome, 'reports', 'old.md')))
  check('the old home directory is gone', 'false', existsSync(legacyHome))
  check('the new home is the default path', 'true', newHome === join(dshHome, 'wrainrock-daemon'))
  check('the legacy unit was removed', 'false', existsSync(join(unitDir, testCase.units[0])))
  check('its enable link was removed', 'false', existsSync(join(wants, testCase.units[0])))
  check('a legacy unit we did not write was left alone', 'true', existsSync(join(unitDir, testCase.units[1])))
  check('the new unit was written', 'true', existsSync(join(unitDir, NEW_UNIT)))
  check('it carries the new marker', 'true',
    readFileSync(join(unitDir, NEW_UNIT), 'utf8').includes(NEW_MARKER))
  check('it is enabled', 'true', lstatSync(join(wants, NEW_UNIT)).isSymbolicLink())
  check('exactly one unit is enabled', '1',
    [...testCase.units, NEW_UNIT].filter((u) => existsSync(join(wants, u))).length)
  check('the migration was reported', 'true', (result.migrated ?? []).length > 0)
  check('install stayed ok', 'true', result.ok === true)
  console.log('')
}

if (failed === 0) {
  console.log('migration test passed')
  rmSync(ROOT, { recursive: true, force: true })
} else {
  console.log(`migration test failed (scratch kept in ${ROOT})`)
}
process.exit(failed)
